export function getComplexRoleKnowledge(roleId: RoleId): ComplexRoleKnowledge | undefined {
  const canonicalRoleId = roleIdAliases[roleId] ?? roleId
  return complexRoleKnowledge.find((item) => item.roleId === canonicalRoleId)
}

export function roleKnowledgeForAI(roleId: RoleId): AIRoleKnowledgeBrief | undefined {
  const knowledge = getComplexRoleKnowledge(roleId)
  if (!knowledge) return undefined
  return {
    roleId: knowledge.roleId,
    title: knowledge.title,
    riskTags: knowledge.riskTags,
    requiredContext: knowledge.requiredContext.slice(0, 4),
    reminders: knowledge.reminders.slice(0, 3),
    aiCannot: knowledge.aiCannot.slice(0, 4),
  }
}

