import { expect, test } from '@playwright/test'
const sessionKey = 'botc-copilot-session-v1'
for (const width of [390, 1440]) {
  test(`production defers optional features and loads tutorial on demand ${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    const requested: string[] = []
    const errors: string[] = []
    page.on('request', (request) => requested.push(request.url()))
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await expect(page.locator('.dashboard')).toBeVisible()
    await expect.poll(() => page.evaluate((key) => localStorage.getItem(key), sessionKey)).not.toBeNull()
    expect(requested.filter((url) => /\/(BeginnerTutorialSheet|SetupPanel|NightWorkbench|DayWorkbench|GameEndSheet|IdentityDealSheet|ScriptLibrarySheet|PublicChatTimerPage)-.*\.js/.test(url))).toEqual([])
    expect(requested.filter((url) => /\/0[1-6]-(dashboard|setup|identity|night|day|review)-/.test(url))).toEqual([])
    const before = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!), sessionKey)
    await page.getByRole('button', { name: '新手教程', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '新手教程', exact: true })
    await expect(dialog.getByRole('button', { name: '下一步', exact: true })).toBeVisible()
    expect(requested.some((url) => /BeginnerTutorialSheet-.*\.js/.test(url))).toBe(true)
    await dialog.evaluate(async (element) => { await Promise.all(element.getAnimations().map((animation) => animation.finished.catch(() => undefined))) })
    const bounds = await dialog.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width + 1)
    expect((await dialog.getByRole('heading', { name: '新手教程' }).boundingBox())!.y).toBeGreaterThanOrEqual(0)
    await page.screenshot({ path: testInfo.outputPath('tutorial-loaded.png') })
    await dialog.getByRole('button', { name: '下一步', exact: true }).click()
    await dialog.getByRole('button', { name: '关闭新手教程' }).click()
    await page.getByRole('button', { name: '新手教程', exact: true }).click()
    await expect(dialog.getByText('第 1 步，共 6 步', { exact: true })).toBeVisible()
    const after = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!), sessionKey)
    expect(after.timeline).toEqual(before.timeline)
    expect(errors).toEqual([])
  })
}
test('production chunk failure can be cancelled without resetting the session', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.route('**/assets/BeginnerTutorialSheet-*.js', (route) => route.abort('failed'))
  await page.goto('/')
  await expect(page.locator('.dashboard')).toBeVisible()
  await expect.poll(() => page.evaluate((key) => localStorage.getItem(key), sessionKey)).not.toBeNull()
  const before = await page.evaluate((key) => localStorage.getItem(key), sessionKey)
  await page.getByRole('button', { name: '新手教程', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText(/当前对局未被重置/)
  await page.screenshot({ path: testInfo.outputPath('chunk-failure.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '返回本局', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '新手教程' })).toBeHidden()
  expect(await page.evaluate((key) => localStorage.getItem(key), sessionKey)).toBe(before)
  await page.unroute('**/assets/BeginnerTutorialSheet-*.js')
})
