import { expect, test, type Page } from '@playwright/test'

const read = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('botc-copilot-session-v1')!))
async function prepare(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '智能配板与调整', exact: true }).click()
  await page.getByRole('searchbox').fill('说书人之怒')
  await page.getByRole('combobox', { name: '开局板子', exact: true }).selectOption({ label: '说书人之怒' })
  await page.getByRole('button', { name: '12人', exact: true }).click()
  await page.getByRole('button', { name: '开始配板', exact: true }).click()
  await page.locator('.setup-candidate').filter({ has: page.getByRole('heading', { name: '说书人之怒 · 均衡', exact: true }) }).getByRole('button', { name: '选择这套配板', exact: true }).click()
  await expect(page.getByRole('button', { name: '确认配板', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '1号 罂粟种植者', exact: true }).click()
  await page.getByRole('button', { name: '2号 失忆者', exact: true }).click()
  await page.getByRole('button', { name: '更换角色', exact: true }).click()
  await page.getByRole('button', { name: '9号 食人族', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '更换9号角色', exact: true })
  await editor.getByRole('button', { name: /^博学者/ }).click()
  await editor.getByRole('button', { name: '应用替换', exact: true }).click()
  await page.getByRole('group', { name: '1号 失忆者开局准备', exact: true }).getByRole('textbox').fill('合成测试能力：每晚选择一人，反馈由说书人确认。')
  const pixie = page.getByRole('group', { name: '4号 小精灵开局准备', exact: true })
  await pixie.getByRole('combobox', { name: '实际标记的镇民玩家', exact: true }).selectOption('9')
  await pixie.getByRole('combobox', { name: '计划告知角色（夜间复核）', exact: true }).selectOption('philosopher')
  await page.getByRole('group', { name: '5号 解谜大师开局准备', exact: true }).getByRole('combobox').selectOption('7')
  await page.getByRole('group', { name: '6号 灵言师开局准备', exact: true }).getByRole('textbox').fill('合成关键词')
  await page.getByRole('group', { name: '8号 炼金术士开局准备', exact: true }).getByRole('combobox').selectOption('cerenovus')
  const lunatic = page.getByRole('group', { name: '10号 疯子开局准备', exact: true })
  await lunatic.getByRole('combobox', { name: '以为自己是', exact: true }).selectOption('vortex')
  await lunatic.getByRole('checkbox', { name: '1号假爪牙候选 失忆者', exact: true }).check()
  await lunatic.getByRole('checkbox', { name: '9号假爪牙候选 博学者', exact: true }).check()
  for (const name of ['僧侣', '魔术师', '博学者']) await lunatic.getByRole('checkbox', { name: `假伪装 ${name}`, exact: true }).check()
  await page.getByRole('button', { name: '确认配板', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '智能配板与调整', exact: true })).toBeHidden()
}

test('复杂开局准备刷新恢复、首夜交接及明确收尾到白天', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await prepare(page)
  await expect.poll(async () => (await read(page)).openingPreparations?.[0]?.choices?.length).toBe(6)
  const before = await read(page)
  expect(before.openingPreparations[0].choices).toHaveLength(6)
  expect(before.timeline.some((e: { kind: string; seatId: number; after?: { drunk: boolean } }) => e.kind === 'player_state_changed' && e.seatId === 7 && e.after?.drunk)).toBe(true)
  await page.reload()
  await expect(page.getByRole('button', { name: '进入夜晚', exact: true })).toBeVisible()
  expect((await read(page)).openingPreparations).toEqual(before.openingPreparations)
  await page.getByRole('button', { name: '进入夜晚', exact: true }).click()
  await expect(page.locator('.wake-recorder').getByRole('button', { name: '洗脑师', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '记录结果', exact: true }).click()
  await page.getByRole('button', { name: '确认并下一位', exact: true }).click()
  await page.getByRole('checkbox', { name: '已核对罂粟状态、相认和真恶魔伪装', exact: true }).check()
  await page.getByRole('button', { name: '已核对罂粟规则', exact: true }).click()
  await page.getByRole('button', { name: '确认并下一位', exact: true }).click()
  await expect(page.getByText('假爪牙：1号、9号', { exact: false })).toBeVisible()
  await page.getByRole('checkbox', { name: '已向疯子告知假恶魔、假爪牙及三张假伪装', exact: true }).check()
  await page.getByRole('button', { name: '已完成假信息告知', exact: true }).click()
  await page.getByRole('button', { name: '确认并下一位', exact: true }).click()
  await expect(page.locator('.system-step-roster').getByText(/罂粟种植者有效：不相认/)).toBeVisible()
  await expect(page.locator('.wake-recorder .choice-chip[aria-pressed="true"]')).toHaveCount(3)
  await page.getByRole('checkbox', { name: '已向真恶魔确认其真实恶魔身份，并指出疯子', exact: true }).check()
  await page.getByRole('button', { name: '已给出恶魔信息', exact: true }).click()
  await page.getByRole('button', { name: '确认并下一位', exact: true }).click()
  await page.getByRole('button', { name: '夜间顺序', exact: true }).click()
  await page.getByRole('dialog', { name: '夜间顺序', exact: true }).getByRole('button', { name: /4号小精灵$/ }).click()
  await page.getByRole('button', { name: /^将夜间处理位置切换到/ }).click()
  await page.getByRole('checkbox', { name: '已核对小精灵信息真假、标记来源与当前毒醉', exact: true }).check()
  await page.getByRole('button', { name: '记录结果', exact: true }).click()
  await page.getByRole('button', { name: '确认本项', exact: true }).click()
  await page.getByRole('button', { name: '夜间顺序', exact: true }).click()
  await page.getByRole('dialog', { name: '夜间顺序', exact: true }).locator('.night-queue-list button').last().click()
  await page.getByRole('button', { name: /^将夜间处理位置切换到/ }).click()
  await page.getByRole('button', { name: '已记录', exact: true }).click()
  await page.getByRole('button', { name: '确认最后一项', exact: true }).click()
  expect((await read(page)).phaseSegments.some((p: { kind: string }) => p.kind === 'day')).toBe(false)
  await page.getByRole('button', { name: '结束夜晚，进入白天', exact: true }).click()
  const close = page.getByRole('dialog', { name: '结束第1夜，进入白天？', exact: true })
  // 此用例只验交接与收尾；无关技能明确记为不处理，不冒充完整对局。
  while (await close.getByRole('button', { name: '本夜不处理', exact: true }).count()) {
    await close.getByRole('button', { name: '本夜不处理', exact: true }).first().click()
    await close.getByLabel('不处理原因', { exact: true }).fill('浏览器交接回归，不执行本项技能。')
    await close.getByRole('button', { name: '确认不处理', exact: true }).click()
  }
  await close.getByRole('button', { name: '确认结束，进入白天', exact: true }).click()
  await expect(page.locator('.day-workbench')).toBeVisible()
  expect((await read(page)).phaseSegments.filter((p: { kind: string; closedAt?: string }) => p.kind === 'day' && !p.closedAt)).toHaveLength(1)
  await page.reload()
  await page.getByRole('button', { name: /^进入白天/ }).click()
  await page.getByRole('button', { name: '记技能/事件', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择9号为发动者', exact: true })).toHaveAccessibleDescription('博学者 · 存活')
  await expect(page.getByRole('button', { name: '选择7号为目标', exact: true })).toHaveAccessibleDescription('僧侣 · 存活 · 醉酒')
  expect(await page.getByRole('button', { name: '选择9号为发动者', exact: true }).evaluate(n => {
    const card = n.getBoundingClientRect(), text = n.querySelector('small')!.getBoundingClientRect()
    return text.top >= card.top && text.bottom <= card.bottom && card.height >= 82
  })).toBe(true)
  await page.getByRole('button', { name: '选择9号为发动者', exact: true }).click()
  await expect(page.locator('.savant-drafts li small')).toHaveCount(2)
  expect((await page.locator('.savant-drafts li small').allTextContents()).every(line => line.startsWith('假'))).toBe(true)
  await page.getByRole('button', { name: '换一组信息', exact: true }).click()
  await page.getByRole('button', { name: '采用到待确认记录', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('savant-private-information.png') })
  await page.getByRole('button', { name: '记录技能', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '白天记录', exact: true })).toBeHidden()
  expect(errors).toEqual([])
})
