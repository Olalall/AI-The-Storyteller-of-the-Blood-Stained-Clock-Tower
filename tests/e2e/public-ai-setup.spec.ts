import { expect, test } from '@playwright/test'

const sessionKey = 'botc-copilot-session-v1'
for (const count of [7, 12, 15]) test(`${count}人更多配板、换批、确认和刷新保留`, async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.dashboard')).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: '智能配板与调整' }).click()
  await page.getByRole('combobox', { name: '开局板子', exact: true }).selectOption('shuo-shu-ren-zhi-nu')
  await page.getByRole('button', { name: `${count}人`, exact: true }).click()
  await page.getByRole('button', { name: '开始配板', exact: true }).click()
  await expect(page.locator('.setup-candidate')).toHaveCount(3)
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}').playerCount, sessionKey)).toBe(count)
  const saved = await page.evaluate(key => localStorage.getItem(key), sessionKey)
  const combos = () => page.locator('.setup-candidate__roles').evaluateAll(lists => lists.map(list => Array.from(list.querySelectorAll('strong')).map(role => role.textContent).sort().join(',')))
  const first = await combos()
  expect(new Set(first).size).toBe(3)
  await page.getByRole('button', { name: '换一批', exact: true }).click()
  const next = await combos()
  expect(next.every(combo => !first.includes(combo))).toBe(true)
  await page.getByRole('button', { name: '更多方案', exact: true }).click()
  await expect(page.locator('.setup-candidate')).toHaveCount(6)
  expect(new Set(await combos()).size).toBe(6)
  expect(await page.evaluate(key => localStorage.getItem(key), sessionKey)).toBe(saved)
  for (const name of ['换一批', '更多方案']) {
    const bounds = await page.getByRole('button', { name, exact: true }).boundingBox()
    // Transformed 44px controls can round down by a fraction of a CSS pixel.
    expect(bounds!.height + 0.01).toBeGreaterThanOrEqual(44)
  }
  expect(await page.locator('.sheet-content--setup').evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
  await page.locator('.setup-candidate').first().getByRole('button', { name: '查看详情', exact: true }).click()
  await expect(page.getByRole('heading', { name: /说书人之怒/ })).toBeVisible()
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await page.locator('.setup-candidate').first().getByRole('button', { name: '选择这套配板', exact: true }).click()
  await expect(page.locator('.setup-panel__draft')).toBeVisible()
  await page.locator('.setup-panel__footer .ui-button--primary').click()
  await expect(page.locator('.setup-panel')).toBeHidden()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}').timeline?.some((entry: { kind: string }) => entry.kind === 'setup_confirmed'), sessionKey)).toBe(true)
  const confirmed = await page.evaluate(key => localStorage.getItem(key), sessionKey)
  expect(JSON.parse(confirmed!).timeline.some((entry: { kind: string }) => entry.kind === 'setup_confirmed')).toBe(true)
  await page.reload()
  await expect(page.locator('.dashboard')).toBeVisible({ timeout: 30_000 })
  expect(await page.evaluate(key => localStorage.getItem(key), sessionKey)).toBe(confirmed)
})

test('新设备免口令使用 AI，推荐和换批不改对局', async ({ page }) => {
  await page.route('**/api/settings/ai', route => route.fulfill({ json: { settings: { mode: 'backend_proxy', provider: 'openai-compatible', baseUrl: '/api/ai', model: '服务器私有模型', apiKeyConfigured: true }, access: { required: false, authorized: true } } }))
  await page.route('**/api/ai/setup-advice', async route => {
    const input = route.request().postDataJSON()
    expect(input.candidates).toHaveLength(3)
    expect(route.request().headers()['cookie']).toBeUndefined()
    await route.fulfill({ json: { accepted: true, data: { draft: { provider: 'openai-compatible', draftOnly: true, confidence: 'medium', recommendedCandidateIds: input.candidates.map((c: { id: string }) => c.id).reverse(), reasons: ['测试推荐'], warnings: [] } } } })
  })
  await page.goto('/')
  await expect(page.locator('.dashboard')).toBeVisible({ timeout: 30_000 })
  await page.getByRole('button', { name: '智能配板与调整' }).click()
  await page.getByRole('button', { name: '开始配板', exact: true }).click()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}').playerCount, sessionKey)).toBe(12)
  const before = await page.evaluate(key => localStorage.getItem(key), sessionKey)
  const reply = page.waitForResponse(response => response.url().endsWith('/api/ai/setup-advice'))
  await page.getByRole('button', { name: 'AI推荐', exact: true }).click()
  expect((await reply).status()).toBe(200)
  await expect(page.getByText('AI草稿', { exact: true })).toBeVisible()
  await expect(page.getByText('AI首选', { exact: true })).toBeVisible()
  await expect(page.getByLabel('AI 访问口令', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '换一批', exact: true }).click()
  await expect(page.getByText('AI首选', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(key => localStorage.getItem(key), sessionKey)).toBe(before)
})
