import { createPrototypeGameSession } from '../../src/features/game-session/data/createPrototypeSession'
import { expect, test, type Page } from '@playwright/test'

const key = 'botc-copilot-session-v1'
async function read(page: Page) { return page.evaluate((key) => JSON.parse(localStorage.getItem(key)!), key) }
for (const width of [390, 1440]) {
  test(`夜晚收尾与状态待办 ${width}px`, async ({ page }, testInfo) => {
    test.setTimeout(60000)
    await page.setViewportSize({ width, height: 900 })
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await page.evaluate(({ key, session }) => {
      session.nightRuns[session.activeNightRunId].privacyShielded = false
      localStorage.setItem(key, JSON.stringify(session))
    }, { key, session: createPrototypeGameSession() })
    await page.reload()
    await page.getByRole('button', { name: '进入夜晚' }).click()
    const baseline = await read(page)
    const cursor = baseline.nightRuns[baseline.activeNightRunId].activeCursorId
    await page.getByRole('button', { name: '检查并关闭' }).click()
    const close = page.getByRole('dialog', { name: '关闭第3夜？' })
    await expect(close).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('night-close-checklist.png'), fullPage: false, animations: 'disabled' })
    await close.getByRole('button', { name: '确认关闭', exact: true }).scrollIntoViewIfNeeded()
    const confirmBox = await close.getByRole('button', { name: '确认关闭', exact: true }).boundingBox()
    expect(confirmBox!.height).toBeGreaterThanOrEqual(44)
    expect(confirmBox!.y + confirmBox!.height).toBeLessThanOrEqual(901)
    await page.screenshot({ path: testInfo.outputPath('night-close-actions.png'), fullPage: false, animations: 'disabled' })
    const row = close.getByRole('list', { name: '未处理夜序' }).locator('li').first()
    const viewName = await row.getByRole('button', { name: /查看/ }).innerText()
    await row.getByRole('button', { name: '本夜不处理', exact: true }).click()
    await expect(row.getByRole('button', { name: '确认不处理' })).toBeDisabled()
    await row.getByLabel('不处理原因').fill('现场核对后本夜无需唤醒')
    await row.getByRole('button', { name: '确认不处理' }).click()
    await expect.poll(async () => (await read(page)).nightRuns[baseline.activeNightRunId].queue.filter((item: { progress: string }) => item.progress === 'skipped').length).toBe(1)
    await close.getByText('本夜不处理 1 项').click()
    await close.getByRole('button', { name: viewName, exact: true }).click()
    await expect(close).toBeHidden()
    await expect.poll(async () => (await read(page)).nightRuns[baseline.activeNightRunId].activeCursorId).toBe(cursor)
    expect((await read(page)).timeline).toEqual(baseline.timeline)

    await page.getByRole('button', { name: '状态待办', exact: true }).click()
    let tasks = page.getByRole('dialog', { name: '状态待办', exact: true })
    await tasks.getByText('添加状态待办', { exact: true }).click()
    const sourceId = baseline.timeline.find((entry: { kind: string }) => entry.kind === 'night_action').id
    await tasks.getByLabel('已确认记录').selectOption(sourceId)
    await tasks.getByLabel('待处理玩家').selectOption('1')
    await tasks.getByLabel('待办内容').fill('核对中毒状态')
    await tasks.getByRole('button', { name: '确认添加待办' }).click()
    await expect(tasks.getByRole('list', { name: '状态待办清单' }).locator('li')).toHaveCount(1)
    await expect.poll(async () => (await read(page)).stateFollowups?.length).toBe(1)
    expect((await read(page)).timeline).toEqual(baseline.timeline)
    await page.screenshot({ path: testInfo.outputPath('state-followups.png'), fullPage: false, animations: 'disabled' })
    await tasks.getByRole('button', { name: '处理状态' }).click()
    const player = page.getByRole('dialog', { name: '1号玩家', exact: true })
    await expect(player).toBeVisible()
    expect((await read(page)).stateFollowups[0].resolution).toBeUndefined()
    await player.getByRole('button', { name: '关闭1号玩家' }).click()
    await expect(tasks).toBeVisible()
    await tasks.getByRole('button', { name: '处理状态' }).click()
    await player.getByRole('button', { name: '中毒', exact: true }).click()
    await player.getByRole('button', { name: '确认状态', exact: true }).click()
    await expect.poll(async () => (await read(page)).stateFollowups[0].resolution?.kind).toBe('applied')
    const after = await read(page)
    expect(after.timeline.length).toBe(baseline.timeline.length + 1)
    expect(after.stateFollowups[0].resolution.entryId).toBe(after.timeline.at(-1).id)
    await page.reload()
    await expect(page.getByRole('button', { name: '状态待办', exact: true })).toBeVisible({ timeout: 21000 })
    await page.getByRole('button', { name: '状态待办', exact: true }).click()
    tasks = page.getByRole('dialog', { name: '状态待办', exact: true })
    await expect(tasks.getByText('待处理 0', { exact: true })).toBeVisible()
    await tasks.getByText('已处理 1', { exact: true }).click()
    await expect(tasks.getByText(/已更新状态/)).toBeVisible()
    const box = await tasks.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width + 1)
    expect(errors).toEqual([])
  })
}
