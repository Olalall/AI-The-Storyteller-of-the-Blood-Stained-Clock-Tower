import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { createTypescriptLoader } from './load-typescript.mjs'
import { verifyRoleDefinitionPins } from './role-definition-pins.mjs'

const load = createTypescriptLoader()
const source = readFileSync('src/domain/scripts/allPacks.ts', 'utf8')
const packs = load(resolve('src/domain/scripts/allPacks.ts')).smartScriptPacks
const { normalizeImportedPack } = load(resolve('src/domain/scripts/normalizeImportedPack.ts'))
const moduleById = new Map([...source.matchAll(/import \{ (\w+) \} from '(\.\/packs\/[^']+)'/g)].map(([, symbol, path]) => [load(resolve('src/domain/scripts', path, 'index.ts'))[symbol].scriptId, { symbol, path }]))
for (const pack of packs) {
  const definitionPath = resolve('src/domain/scripts', moduleById.get(pack.scriptId).path, 'definition.json')
  if (existsSync(definitionPath)) {
    const definition = JSON.parse(readFileSync(definitionPath, 'utf8'))
    if (definition.roleRefs) verifyRoleDefinitionPins(definition, pack.roles)
  }
}
const banner = '// Generated by npm run generate:script-manifest. Do not edit by hand.\n'
const metadata = packs.map(normalizeImportedPack).map(({ scriptId, displayName, playerCounts, knowledgeStatus }) => ({ scriptId, displayName, playerCounts, knowledgeStatus }))
const files = new Map([
  ['scriptManifest.generated.ts', banner + "import type { SmartScriptPack } from './types'\nexport const scriptManifest: readonly Pick<SmartScriptPack, 'scriptId' | 'displayName' | 'playerCounts' | 'knowledgeStatus'>[] = " + JSON.stringify(metadata, null, 2) + '\n'],
  ['scriptLoaders.generated.ts', banner + "import type { SmartScriptPack } from './types'\nexport const scriptLoaders: Record<string, () => Promise<SmartScriptPack>> = {\n" + packs.filter((pack) => pack.scriptId !== 'catfishing').map(({ scriptId }) => {
    const { symbol, path } = moduleById.get(scriptId)
    return `  ${JSON.stringify(scriptId)}: () => import('${path}').then((module) => module.${symbol}),`
  }).join('\n') + '\n}\n'],
])
const requirements = new Map(), remote = new Set()
for (const pack of packs) for (const role of pack.roles) {
  const path = role.iconPath
  if (path.startsWith('/assets/characters/')) requirements.set(path, { roleId: role.id, roleName: role.name, path })
  else if (/^https?:/.test(path)) remote.add(path)
}
files.set('scriptAssets.generated.ts', banner + 'export const scriptAssetProjection = ' + JSON.stringify({ requirements: [...requirements.values()].sort((a, b) => a.path.localeCompare(b.path)), remoteIconCount: remote.size, localDirectory: 'public/assets/characters/', manifestPath: 'public/assets/characters/source-manifest.json' }, null, 2) + '\n')
const kazali = Object.fromEntries(packs.filter(pack => pack.roles.some(role => role.id === 'kazali'))
  .map(pack => [pack.scriptId, pack.roles.filter(role => role.team === 'minion').map(role => role.id).sort()]))
files.set(resolve('server/ai/kazaliMinionRoleIds.generated.ts'), banner + 'export const kazaliMinionRoleIds: Readonly<Record<string, readonly string[]>> = ' + JSON.stringify(kazali, null, 2) + '\n')
for (const [name, content] of files) {
  const file = resolve('src/domain/scripts', name)
  if (process.argv.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error(`${name} is stale; run npm run generate:script-manifest`)
  } else writeFileSync(file, content)
}
console.log(`Script manifest verified: ${packs.length} packs`)
